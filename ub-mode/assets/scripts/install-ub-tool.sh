#!/bin/sh
# Install one ub-mode quality tool into the gc cache.
#
# usage: install-ub-tool.sh <tool> <repo-url> <pinned-commit>
#
# Layout, fixed on purpose so the absolute paths in the ub-mode skill stay
# valid and never collide with gc's own ~/.gc/cache/repos:
#
#   ~/.gc/cache/ub-mode/<tool>/   pinned checkout, with its own .venv
#   ~/.gc/cache/bin/<tool>        launcher the skill calls
#
# Exit 0 when the tool is present and runnable, 2 when it could not be
# installed. There is no warn state: either the gate can run or it cannot.

set -eu

tool=${1:?usage: install-ub-tool.sh <tool> <repo-url> <pinned-commit>}
repo=${2:?usage: install-ub-tool.sh <tool> <repo-url> <pinned-commit>}
commit=${3:?usage: install-ub-tool.sh <tool> <repo-url> <pinned-commit>}

cache=${GC_UB_CACHE:-$HOME/.gc/cache}
root=$cache/ub-mode/$tool
bindir=$cache/bin
launcher=$bindir/$tool

if [ -x "$launcher" ] && [ -x "$root/$tool" ] && [ -x "$root/.venv/bin/python" ]; then
  echo "$tool ready: $launcher"
  exit 0
fi

if ! command -v git >/dev/null 2>&1; then
  echo "$tool needs git on PATH to install; install git and rerun 'gc doctor'"
  exit 2
fi
if ! command -v python3 >/dev/null 2>&1; then
  echo "$tool needs python3 on PATH to install; install Python 3.11+ and rerun 'gc doctor'"
  exit 2
fi
if ! python3 -c 'import sys; raise SystemExit(0 if sys.version_info >= (3, 11) else 1)'; then
  echo "$tool needs Python 3.11 or later; python3 is $(python3 -V 2>&1 | cut -d' ' -f2)"
  exit 2
fi

mkdir -p "$bindir" "$cache/ub-mode"

if [ ! -x "$root/$tool" ]; then
  rm -rf "$root"
  mkdir -p "$root"
  git -C "$root" init -q
  git -C "$root" remote add origin "$repo"
  if ! git -C "$root" fetch -q --depth 1 origin "$commit"; then
    echo "$tool: could not fetch $commit from $repo"
    exit 2
  fi
  git -C "$root" checkout -q FETCH_HEAD || {
    echo "$tool: could not check out $commit"
    exit 2
  }
fi

# The upstream launcher builds its own virtualenv on first run.
if ! "$root/$tool" --help >/dev/null 2>&1; then
  # --help may legitimately exit non-zero; judge by the venv instead.
  if [ ! -x "$root/.venv/bin/python" ]; then
    echo "$tool: bootstrap failed (no $root/.venv); run '$root/$tool --help' to see why"
    exit 2
  fi
fi

cat >"$launcher" <<EOF
#!/bin/sh
# Generated by the ub-mode pack doctor check. Pinned to $commit.
exec "$root/$tool" "\$@"
EOF
chmod +x "$launcher"

echo "$tool ready: $launcher (pinned $commit)"
